    #[derive(Debug, PartialEq)]
    enum TestOutputEvent {
        Begin(u32),
        Value(u32, f64),
        End(u32),
    }

    struct TestOutputEvents {
        accept: bool,
        events: Vec<TestOutputEvent>,
    }

    unsafe extern "C" fn test_output_try_push(
        list: *const clap_output_events_t,
        header: *const clap_event_header_t,
    ) -> bool {
        let output = unsafe { &mut *((*list).ctx as *mut TestOutputEvents) };
        if !output.accept {
            return false;
        }
        let event = match unsafe { (*header).type_ } {
            CLAP_EVENT_PARAM_GESTURE_BEGIN => {
                let event = unsafe { &*(header as *const clap_event_param_gesture_t) };
                TestOutputEvent::Begin(event.param_id)
            }
            CLAP_EVENT_PARAM_VALUE => {
                let event = unsafe { &*(header as *const clap_event_param_value_t) };
                TestOutputEvent::Value(event.param_id, event.value)
            }
            CLAP_EVENT_PARAM_GESTURE_END => {
                let event = unsafe { &*(header as *const clap_event_param_gesture_t) };
                TestOutputEvent::End(event.param_id)
            }
            event_type => panic!("unexpected output event type {event_type}"),
        };
        output.events.push(event);
        true
    }

    fn test_output(output: &mut TestOutputEvents) -> clap_output_events_t {
        clap_output_events_t {
            ctx: (output as *mut TestOutputEvents).cast(),
            try_push: Some(test_output_try_push),
        }
    }

    #[test]
    fn host_handle_queues_parameter_gestures_and_values_in_order() {
        let mut state = TestHostState {
            expose_params: true,
            ..TestHostState::default()
        };
        let host = test_host(&mut state);
        let handle = unsafe { HostHandle::from_raw(&host) };

        assert!(handle.begin_edit(17));
        assert!(handle.perform_edit(17, 0.625));
        assert!(handle.end_edit(17));
        assert_eq!(state.flush_requests, 3);

        let mut output = TestOutputEvents {
            accept: true,
            events: Vec::new(),
        };
        let output_list = test_output(&mut output);
        assert_eq!(unsafe { handle.flush_parameter_events(&output_list) }, 3);
        assert_eq!(
            output.events,
            vec![
                TestOutputEvent::Begin(17),
                TestOutputEvent::Value(17, 0.625),
                TestOutputEvent::End(17),
            ]
        );
        assert_eq!(unsafe { handle.flush_parameter_events(&output_list) }, 0);
    }

    #[test]
    fn rejected_parameter_output_remains_queued_for_retry() {
        let mut state = TestHostState {
            expose_params: true,
            ..TestHostState::default()
        };
        let host = test_host(&mut state);
        let handle = unsafe { HostHandle::from_raw(&host) };
        assert!(handle.perform_edit(9, 0.25));

        let mut output = TestOutputEvents {
            accept: false,
            events: Vec::new(),
        };
        let mut output_list = test_output(&mut output);
        assert_eq!(unsafe { handle.flush_parameter_events(&output_list) }, 0);
        assert!(output.events.is_empty());

        output.accept = true;
        output_list = test_output(&mut output);
        assert_eq!(unsafe { handle.flush_parameter_events(&output_list) }, 1);
        assert_eq!(output.events, vec![TestOutputEvent::Value(9, 0.25)]);
    }

